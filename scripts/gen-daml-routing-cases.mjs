// Generates daml/lute-tests/daml/Lute/Test/RoutingParity.daml from the shared
// router fixtures so the TypeScript router and the Daml model are tested on
// identical cases (spec §47). Run: node scripts/gen-daml-routing-cases.mjs
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const { defaultPolicy, cases } = JSON.parse(readFileSync(new URL("packages/routing/test/cases.json", root), "utf8"));

const dec = (s) => {
  if (!/^\d+(\.\d{1,10})?$/.test(s)) throw new Error(`fixture amount not representable as Daml Decimal: ${s}`);
  return s.includes(".") ? s : `${s}.0`;
};
const reasons = {
  ZERO_OBLIGATION: "ZeroObligation",
  ROUTE_NOT_ALLOWED: "RouteNotAllowed",
  INSUFFICIENT_LIQUIDITY: "InsufficientLiquidity",
  REDEMPTION_CAP_EXCEEDED: "RedemptionCapExceeded",
};
const optional = (v, f) => (v == null ? "None" : `(Some ${f(v)})`);
const text = (s) => JSON.stringify(s);

const checks = cases.map((c) => {
  const policy = { ...defaultPolicy, ...c.input.policy };
  const e = c.expect;
  return `  check ${text(c.name)}
    RoutingInput with
      cash = ${dec(c.input.cash)}
      productive = ${dec(c.input.productive)}
      redeemable = ${dec(c.input.redeemable ?? c.input.productive)}
      obligation = ${dec(c.input.obligation)}
      policy = RoutingPolicy with
        minCashBuffer = ${dec(policy.minCashBuffer)}
        maxRedeemPerExecution = ${optional(policy.maxRedeemPerExecution, dec)}
        allowedRoutes = [${policy.allowedRoutes.join(", ")}]
    ${optional(e.route, (r) => r)} ${optional(e.blockedReason, (r) => reasons[r])}
    ${dec(e.cashUsed)} ${dec(e.shortfall)} ${dec(e.redeemAmount)} ${dec(e.remainingProductive)}`;
});

const out = `-- GENERATED by scripts/gen-daml-routing-cases.mjs from
-- packages/routing/test/cases.json. Do not edit by hand.
module Lute.Test.RoutingParity where

import Daml.Script
import Lute.Routing
import Lute.Types

check : Text -> RoutingInput -> Optional Route -> Optional BlockedReason -> Decimal -> Decimal -> Decimal -> Decimal -> Script ()
check name i route reason cashUsed shortfall redeem remaining =
  case computeFundingRoute i of
    Left err -> abort (name <> ": unexpected input error: " <> err)
    Right r -> do
      assertMsg (name <> ": route " <> show r.route) (r.route == route)
      assertMsg (name <> ": blockedReason " <> show r.blockedReason) (r.blockedReason == reason)
      assertMsg (name <> ": cashUsed " <> show r.cashUsed) (r.cashUsed == cashUsed)
      assertMsg (name <> ": shortfall " <> show r.shortfall) (r.shortfall == shortfall)
      assertMsg (name <> ": redeemAmount " <> show r.redeemAmount) (r.redeemAmount == redeem)
      assertMsg (name <> ": remainingProductive " <> show r.remainingProductive) (r.remainingProductive == remaining)

testRoutingParity : Script ()
testRoutingParity = do
${checks.join("\n")}
`;

writeFileSync(new URL("daml/lute-tests/daml/Lute/Test/RoutingParity.daml", root), out);
console.log(`wrote ${cases.length} routing parity cases`);
